--[[ Body Pull - Core/Assets.lua
	Game code asks for sprites, animation frames and sounds by name and never builds a file path.
	The names and rectangles come from Data/Atlas.lua (generated by the asset build).

	  A:Sprite(tex, name [, flip])      texture + texcoords; returns the sprite's pixel size (atlas px)
	  A:Has(name) / A:Size(name)
	  A:Anim(name)                      { fps, loop, w, h, px, py, frame names... } or nil
	  A:Frame(tex, anim, i, flip)       show frame i (1-based) of an animation
	  A:SoundPath(name), A:MusicPath(name)
	  A.missing                         problems found (shown by /bodypull debug) ]]

local _, ns = ...
local P = ns.P
local A = P:Module("Assets")
local D = ns.Atlas
local TEX = P.MEDIA .. "Tex\\"
local ROOT = "Interface\\AddOns\\" .. P.name .. "\\"

A.missing = {}
A.TEX = TEX

local spr, animSrc = D.spr, D.anim
local tex, texByName = {}, {}
for i, t in ipairs(D.tex) do tex[i] = t texByName[t[1]] = t end
A.texSize = texByName      -- atlas name -> {name, w, h}

local function Missing(what)
	if #A.missing < 40 then A.missing[#A.missing + 1] = what end
end

-- Data/Atlas.lua keeps each sprite as one packed number and each animation as one short string; a record
-- is unpacked the first time it is drawn and kept until the window closes (A:Trim), so the closed game
-- holds only the compact manifest.
local recs, anims = {}, {}
local floor = math.floor

local function Rec(name)
	local r = recs[name]
	if r then return r end
	local v = spr[name]
	if not v then return nil end
	local h = v % 2048 v = floor(v / 2048)
	local w = v % 4096 v = floor(v / 4096)
	local y = v % 4096 v = floor(v / 4096)
	local x = v % 4096
	local t = tex[floor(v / 4096)]
	local aw, ah = t[2], t[3]
	r = { t[1], x, y, w, h, x / aw, (x + w) / aw, y / ah, (y + h) / ah }
	recs[name] = r
	return r
end
A.Rec = function(_, name) return Rec(name) end

local function FrameName(name, i) return ("%s_%02d"):format(name, i) end

-- every frame of every animation must exist: checked once at load, listed rather than drawn blank
for name, src in pairs(animSrc) do
	local n = tonumber(src:match("(%d+)$")) or 0
	if n < 1 then Missing("animation " .. name .. " has no frames") end
	for i = 1, n do
		if not spr[FrameName(name, i)] then Missing("animation " .. name .. " frame " .. i) end
	end
end

function A:Has(name) return spr[name] ~= nil end
function A:Size(name)
	local s = Rec(name)
	if s then return s[4], s[5] end
	return 0, 0
end

function A:Sprite(t, name, flip)
	local s = Rec(name)
	if not s then
		Missing("sprite " .. tostring(name))
		t:SetColorTexture(1, 0, 1, 0.5)
		return 8, 8
	end
	t:SetTexture(TEX .. s[1])
	if flip then t:SetTexCoord(s[7], s[6], s[8], s[9]) else t:SetTexCoord(s[6], s[7], s[8], s[9]) end
	return s[4], s[5]
end

-- only the coordinates (same atlas): the per-frame path of an animation, no texture reload
function A:Coords(t, name, flip)
	local s = Rec(name)
	if not s then return end
	if flip then t:SetTexCoord(s[7], s[6], s[8], s[9]) else t:SetTexCoord(s[6], s[7], s[8], s[9]) end
end

function A:AtlasOf(name)
	local s = Rec(name)
	return s and s[1]
end

-- { fps, loop, w, h, px, py, frame names... }
function A:Anim(name)
	local a = anims[name]
	if a then return a end
	local src = animSrc[name]
	if not src then return nil end
	local fps, loop, w, h, px, py, n = src:match("^(%S+) (%d) (%d+) (%d+) (%S+) (%S+) (%d+)$")
	a = { fps = tonumber(fps), loop = loop == "1", w = tonumber(w), h = tonumber(h), px = tonumber(px), py = tonumber(py) }
	for i = 1, tonumber(n) do a[i] = FrameName(name, i) end
	anims[name] = a
	return a
end

function A:Frame(t, a, i, flip)
	local name = a[i]
	if name then self:Coords(t, name, flip) end
end

-- the window closed: forget the unpacked records (they come back on the next draw)
function A:Trim()
	wipe(recs)
	wipe(anims)
end

function A:SoundPath(name)
	local s = D.snd[name]
	if not s or s.music then return nil end
	return ROOT .. (s[1]:gsub("/", "\\")), s
end

function A:MusicPath(name)
	local s = D.snd[name]
	if not s or not s.music then return nil end
	return ROOT .. (s[1]:gsub("/", "\\"))
end
